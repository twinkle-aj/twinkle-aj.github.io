/**
 * Core Language Translation Dispatcher
 */
window.currentLanguage = localStorage.getItem('romantic_story_lang') || 'en';

window.setLanguage = function(lang, smooth = true) {
  if (!window.TRANSLATIONS[lang]) lang = 'en';
  window.currentLanguage = lang;
  localStorage.setItem('romantic_story_lang', lang);

  document.documentElement.lang = lang;

  const t = window.TRANSLATIONS[lang];

  // Helper function to update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      if (smooth) {
        el.style.transition = 'opacity 0.2s ease';
        el.style.opacity = '0.5';
        setTimeout(() => {
          el.innerHTML = t[key];
          el.style.opacity = '1';
        }, 120);
      } else {
        el.innerHTML = t[key];
      }
    }
  });

  // Update elements with data-i18n-attr (e.g. data-i18n-attr="title:key,placeholder:key")
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    const pairs = el.getAttribute('data-i18n-attr').split(',');
    pairs.forEach(pair => {
      const [attr, key] = pair.split(':').map(s => s.trim());
      if (attr && key && t[key] !== undefined) {
        el.setAttribute(attr, t[key]);
      }
    });
  });

  // Update active state on Language Switcher Buttons
  document.querySelectorAll('.lang-pill-btn, .lang-card-btn').forEach((btn) => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Sync floating bubble photos if available
  if (window.photoEngine && window.photoEngine.photos && t.bubble_photos) {
    window.photoEngine.photos.forEach((photo, idx) => {
      if (t.bubble_photos[idx]) {
        photo.title = t.bubble_photos[idx].title;
        photo.note = t.bubble_photos[idx].note;
      }
    });
  }

  // Dispatch global event for other components (like countdown timer)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, t } }));
};
